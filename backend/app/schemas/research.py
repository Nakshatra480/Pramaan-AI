from __future__ import annotations

import uuid
from datetime import date, datetime
from typing import Literal

from pydantic import Field, field_validator

from app.db.models import ClaimStatus, ResearchMode, ResearchStatus, SourceType, StepStatus, Visibility
from app.schemas.common import ApiModel

Channel = Literal["web", "academic", "project", "library"]


class ResearchCreate(ApiModel):
    query: str = Field(min_length=8, max_length=2000)
    project_id: uuid.UUID | None = None
    mode: ResearchMode = ResearchMode.standard
    sources: list[Channel] = Field(default_factory=lambda: list[Channel](["web", "academic"]), min_length=1, max_length=4)
    # "Research with this": build the report from these documents first (web/scholarly sources only supplement).
    document_ids: list[uuid.UUID] = Field(default_factory=list, max_length=10)

    @field_validator("query")
    @classmethod
    def _strip(cls, v: str) -> str:
        v = " ".join(v.split())
        if len(v) < 8:
            raise ValueError("Ask a complete question.")
        return v

    @field_validator("sources")
    @classmethod
    def _dedupe(cls, v: list[str]) -> list[str]:
        return list(dict.fromkeys(v))


class ResearchCreated(ApiModel):
    research_id: uuid.UUID
    status: ResearchStatus


class Metrics(ApiModel):
    sources: int = 0
    evidence: int = 0
    candidate_claims: int = 0
    verified_claims: int = 0


class StepOut(ApiModel):
    id: str
    label: str
    status: StepStatus
    detail: str | None = None


class SourceOut(ApiModel):
    id: uuid.UUID
    title: str
    domain: str
    url: str
    publisher: str
    authors: list[str]
    published_at: date | None
    type: SourceType
    relevance: float
    doi: str | None
    abstract: str | None


class EvidenceOut(ApiModel):
    id: uuid.UUID
    source_id: uuid.UUID
    passage: str
    relevance: float
    location: str | None


class ClaimOut(ApiModel):
    id: uuid.UUID
    text: str
    status: ClaimStatus
    confidence: float
    source_ids: list[uuid.UUID]
    evidence_ids: list[uuid.UUID]


class CitationOut(ApiModel):
    index: int
    source_id: uuid.UUID


class KeyFinding(ApiModel):
    title: str
    body: str
    claim_ids: list[uuid.UUID] = []


class ReportSection(ApiModel):
    heading: str
    paragraphs: list[str]


class ReportBlock(ApiModel):
    """One block of a paper section. Which fields are set depends on `type`."""

    type: Literal["paragraph", "list", "table", "diagram", "figure"]
    text: str | None = None  # paragraph
    items: list[str] | None = None  # list
    caption: str | None = None  # table, diagram, figure
    columns: list[str] | None = None  # table
    rows: list[list[str]] | None = None  # table (citation markers end each row's last cell)
    code: str | None = None  # diagram: Mermaid, generated by the server
    url: str | None = None  # figure: the image
    credit: str | None = None  # figure: who published it
    source_url: str | None = None  # figure: the page it appears on
    source_index: int | None = None  # figure: that page's citation number


class PaperSection(ApiModel):
    heading: str
    blocks: list[ReportBlock]


class ReportOut(ApiModel):
    # "paper": title, keywords, abstract (`summary`) and numbered `sections`. "legacy": reports written before
    # the paper format (summary, findings, analysis) — still stored and shown as they were.
    format: Literal["legacy", "paper"] = "legacy"
    title: str | None = None
    keywords: list[str] = []
    summary: list[str]
    findings: list[KeyFinding]
    analysis: list[ReportSection]
    sections: list[PaperSection] = []
    limitations: list[str]
    citations: list[CitationOut]


class FollowUpSource(ApiModel):
    """A source cited by a follow-up answer; the answer's [n] is the n-th entry."""

    title: str
    url: str
    domain: str
    publisher: str
    type: SourceType
    published_at: date | None = None
    authors: list[str] = []
    origin: Literal["report", "web", "academic", "wikipedia"]
    source_id: uuid.UUID | None = None  # set when it's one of the report's own sources (opens in the panel)


class FollowUpOut(ApiModel):
    id: uuid.UUID
    question: str
    created_at: datetime
    status: Literal["running", "complete", "failed"]
    answer: list[str]
    # "answer": answered from the report + fresh search. "revision": the report is being regenerated
    # with the requested changes as a new research session (`revision_id`); the original stays as it is.
    kind: Literal["answer", "revision"] = "answer"
    revision_id: uuid.UUID | None = None
    sources: list[FollowUpSource] = []


class ResearchSummaryOut(ApiModel):
    id: uuid.UUID
    title: str
    query: str
    mode: ResearchMode
    channels: list[Channel]
    project_id: uuid.UUID | None
    status: ResearchStatus
    created_at: datetime
    completed_at: datetime | None
    saved: bool
    visibility: Visibility
    share_id: str | None
    metrics: Metrics
    error_code: str | None = None
    parent_id: uuid.UUID | None = None  # set on a revision: the research it regenerates
    revision_instructions: str | None = None
    document_ids: list[uuid.UUID] = []  # documents the report was built from first ("Research with this")


class ResearchOut(ResearchSummaryOut):
    steps: list[StepOut]
    sources: list[SourceOut]
    source_ids: list[uuid.UUID]
    evidence: list[EvidenceOut]
    claims: list[ClaimOut]
    report: ReportOut | None
    follow_ups: list[FollowUpOut]
    progress: float


class ResearchUpdate(ApiModel):
    title: str | None = Field(default=None, min_length=1, max_length=300)
    saved: bool | None = None
    project_id: uuid.UUID | None = None
    move_project: bool = False  # explicit flag so `projectId: null` can mean "remove from project"


class ShareUpdate(ApiModel):
    visibility: Visibility


class ShareOut(ApiModel):
    visibility: Visibility
    share_id: str | None


class FollowUpCreate(ApiModel):
    question: str = Field(min_length=3, max_length=1000)


class ProgressEvent(ApiModel):
    """Safe operational progress — never model reasoning."""

    type: str
    status: ResearchStatus
    message: str
    progress: int
    steps: list[StepOut]
    metrics: Metrics
    source_ids: list[uuid.UUID]
